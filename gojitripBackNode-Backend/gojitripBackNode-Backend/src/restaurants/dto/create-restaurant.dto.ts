import { IsArray, IsNotEmpty, IsOptional, IsString } from 'class-validator';

export class CreateRestaurantDto {
  // ============================================================
  // RESTAURANT NAME
  // ============================================================

  @IsString()
  @IsNotEmpty()
  restaurantName: string;

  // ============================================================
  // LOCATION
  // ============================================================

  @IsString()
  @IsNotEmpty()
  location: string;

  // ============================================================
  // CONTACT DETAILS
  // ============================================================

  @IsString()
  @IsNotEmpty()
  contactDetails: string;

  // ============================================================
  // CUISINE TYPES
  // ============================================================

  @IsArray()
  @IsString({ each: true })
  cuisineTypes: string[];

  // ============================================================
  // OPENING HOURS
  // ============================================================

  @IsString()
  @IsNotEmpty()
  openingHours: string;

  // ============================================================
  // PRICE RANGE
  // ============================================================

  @IsString()
  @IsNotEmpty()
  priceRange: string;

  // ============================================================
  // IMAGE URL
  // ============================================================

  @IsOptional()
  @IsString()
  imageUrl?: string | null;

  // ============================================================
  // PHOTOS
  // ============================================================

  @IsOptional()
  @IsArray()
  @IsString({ each: true })
  photos?: string[];

  // ============================================================
  // RECOMMENDED DISHES
  // ============================================================

  @IsOptional()
  @IsArray()
  @IsString({ each: true })
  recommendedDishes?: string[];

  // ============================================================
  // APPROVAL STATUS
  // ============================================================

  @IsOptional()
  @IsString()
  approvalStatus?: string;

  // ============================================================
  // CREATED BY
  // ============================================================

  @IsOptional()
  @IsString()
  createdByName?: string;
}
